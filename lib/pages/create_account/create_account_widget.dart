  String _sanitizeGeneric(String value) =>
      value.replaceAll(RegExp(r'[\u0000-\u001F\u007F]'), '').trim();

  String _sanitizeName(String value) =>
      _sanitizeGeneric(value).replaceAll(RegExp(r'\s+'), ' ');

  String _sanitizeEmail(String value) =>
      _sanitizeGeneric(value).toLowerCase().replaceAll(RegExp(r'\s+'), '');

  String _sanitizePhone(String value) =>
      _sanitizeGeneric(value).replaceAll(RegExp(r'[^0-9+]'), '');

  String _sanitizePassword(String value) => _sanitizeGeneric(value);

  void _normalizeAuthInputs() {
    _model.firstnameTextController.text =
        _sanitizeName(_model.firstnameTextController.text);
    _model.lastnameTextController.text =
        _sanitizeName(_model.lastnameTextController.text);
    _model.phoneTextController.text =
        _sanitizePhone(_model.phoneTextController.text);
    _model.emailAddressTextController.text =
        _sanitizeEmail(_model.emailAddressTextController.text);
    _model.passwordTextController.text =
        _sanitizePassword(_model.passwordTextController.text);
    _model.passwordConfirmTextController.text =
        _sanitizePassword(_model.passwordConfirmTextController.text);
  }

  String? _validateName(BuildContext context, String? value) {
    final sanitized = _sanitizeName(value ?? '');
    if (sanitized.isEmpty) {
      return 'This field is required';
    }
    if (!RegExp(r"^[A-Za-z][A-Za-z '\-]{1,49}$").hasMatch(sanitized)) {
      return 'Use letters only';
    }
    return null;
  }

  String? _validatePhone(BuildContext context, String? value) {
    final sanitized = _sanitizePhone(value ?? '');
    if (sanitized.isEmpty) {
      return 'Phone is required';
    }
    if (!RegExp(r'^\+?[0-9]{7,15}$').hasMatch(sanitized)) {
      return 'Enter a valid phone number';
    }
    return null;
  }

  String? _validateEmail(BuildContext context, String? value) {
    final sanitized = _sanitizeEmail(value ?? '');
    if (sanitized.isEmpty) {
      return 'Email is required';
    }
    if (!RegExp(r'^[^\s@]+@[^\s@]+\.[^\s@]+$').hasMatch(sanitized)) {
      return 'Enter a valid email';
    }
    return null;
  }

  String? _validatePassword(BuildContext context, String? value) {
    final sanitized = _sanitizePassword(value ?? '');
    if (sanitized.isEmpty) {
      return 'Password is required';
    }
    if (sanitized.length < 8) {
      return 'Password must be at least 8 characters';
    }
    return null;
  }

  String? _validatePasswordConfirm(BuildContext context, String? value) {
    final confirm = _sanitizePassword(value ?? '');
    final password = _sanitizePassword(_model.passwordTextController.text);
    if (confirm.isEmpty) {
      return 'Confirm your password';
    }
    if (confirm != password) {
      return 'Passwords do not match';
    }
    return null;
  }

